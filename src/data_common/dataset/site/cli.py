from __future__ import annotations

import json
from pathlib import Path

import rich_click as click

from . import create_app
from .freezer import build_site, build_targets, check_site


@click.group("site")
def site_cli() -> None:
    """
    Build and serve the static dataset website.
    """


@site_cli.command("build")
@click.option("--output", type=click.Path(path_type=Path), default=None)
@click.option("--check-links/--no-check-links", default=True)
def build_command(output: Path | None, check_links: bool) -> None:
    """
    Build the complete static site.
    """
    app = create_app()
    report = build_site(app, output, check_links=check_links)
    click.echo(
        f"Built {report.page_count} pages, {report.data_file_count} data files "
        f"and {report.asset_count} assets in {report.output_dir}"
    )


@site_cli.command("check")
def check_command() -> None:
    """
    Build into a temporary directory and validate the result.
    """
    report = check_site(create_app())
    click.echo(
        f"Checked {report.page_count} pages and {report.data_file_count} data files"
    )


@site_cli.command("routes")
@click.option("--json", "as_json", is_flag=True)
def routes_command(as_json: bool) -> None:
    """
    List every page generated by the static builder.
    """
    app = create_app()
    targets = build_targets(
        app.extensions["dataset_catalogue"],
        app.config["SITE_SETTINGS"],
    )
    if as_json:
        click.echo(
            json.dumps(
                [
                    {
                        "url": target.url,
                        "destination": str(target.destination),
                    }
                    for target in targets
                ],
                indent=2,
            )
        )
        return
    for target in targets:
        click.echo(f"{target.url} -> {target.destination}")


@site_cli.command("migrate")
@click.option(
    "--repo-root",
    type=click.Path(path_type=Path, file_okay=False),
    default=None,
)
@click.option("--apply", "apply_changes", is_flag=True)
@click.option("--force", is_flag=True)
@click.option(
    "--ignore-published",
    is_flag=True,
    help="Add data/packages/_published to .gitignore.",
)
def migrate_command(
    repo_root: Path | None,
    apply_changes: bool,
    force: bool,
    ignore_published: bool,
) -> None:
    """
    Convert a Jekyll repository to the shared Flask site layout.
    """
    from .migration import migrate_repository

    report = migrate_repository(
        repo_root=repo_root,
        apply=apply_changes,
        force=force,
        ignore_published=ignore_published,
    )
    prefix = "Applied" if report.applied else "Would apply"
    for action in report.actions:
        click.echo(f"{prefix}: {action}")
    for warning in report.warnings:
        click.echo(f"Warning: {warning}", err=True)
    if not report.changed:
        click.echo("Repository is already migrated.")


@site_cli.command("serve")
@click.option("--host", default="127.0.0.1", show_default=True)
@click.option("--port", default=5000, type=int, show_default=True)
@click.option("--debug/--no-debug", default=True)
def serve_command(host: str, port: int, debug: bool) -> None:
    """
    Run the dataset site locally with Flask.
    """
    app = create_app()
    settings = app.config["SITE_SETTINGS"]
    click.echo(f"Serving at http://{host}:{port}{settings.base_url}/")
    app.run(host=host, port=port, debug=debug)
