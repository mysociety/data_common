from __future__ import annotations

from pathlib import Path
from typing import NamedTuple

from pydantic import BaseModel, ConfigDict, Field, RootModel

from ..package_models import DataPackageExtras
from .schemas import AnalysisBundleManifest


class VersionLabels(NamedTuple):
    """
    Group a semantic version with all labels resolving to it.
    """

    full_version: str
    labels: tuple[str, ...]


class BuildTarget(NamedTuple):
    """
    Describe one route and its static output destination.
    """

    url: str
    destination: Path
    mimetype: str = "text/html"


class BuildReport(NamedTuple):
    """
    Summarise the files generated by one static-site build.
    """

    output_dir: Path
    page_count: int
    data_file_count: int
    asset_count: int


class MissingLink(NamedTuple):
    """
    Describe an unresolved link in a generated HTML page.
    """

    page: Path
    link: str


class NamedLink(BaseModel):
    """
    Represent a titled contributor, source, or licence link.
    """

    model_config = ConfigDict(extra="allow", frozen=True)

    title: str = ""
    path: str = ""
    name: str = ""


class FieldConstraints(BaseModel):
    """
    Represent constraints displayed for one published field.
    """

    model_config = ConfigDict(extra="allow", frozen=True)

    unique: bool = False
    required: bool = False
    enum: list[str | int | float | bool] = Field(default_factory=list)


class PublishedField(BaseModel):
    """
    Represent one field in a published resource schema.
    """

    model_config = ConfigDict(extra="allow", frozen=True)

    name: str
    type: str = "string"
    description: str = ""
    constraints: FieldConstraints = Field(default_factory=FieldConstraints)


class PublishedSchema(BaseModel):
    """
    Represent the fields belonging to one published resource.
    """

    model_config = ConfigDict(extra="allow", frozen=True)

    fields: list[PublishedField] = Field(default_factory=list)


class PublishedResource(BaseModel):
    """
    Represent one downloadable resource in a published datapackage.
    """

    model_config = ConfigDict(extra="allow", frozen=True)

    name: str
    path: str
    title: str = ""
    description: str = ""
    resource_schema: PublishedSchema = Field(
        default_factory=PublishedSchema,
        alias="schema",
    )

    @property
    def schema(self) -> PublishedSchema:
        """
        Return the resource schema using its datapackage field name.
        """
        return self.resource_schema


class PublishedDataset(BaseModel):
    """
    Validate a datapackage.json consumed by the static site.
    """

    model_config = ConfigDict(extra="allow", frozen=True)

    name: str
    title: str | None = None
    description: str = ""
    version: str
    contributors: list[NamedLink] = Field(default_factory=list)
    sources: list[NamedLink] = Field(default_factory=list)
    licenses: list[NamedLink] = Field(default_factory=list)
    custom: DataPackageExtras = Field(default_factory=DataPackageExtras)
    resources: list[PublishedResource] = Field(default_factory=list)


class DownloadPage(BaseModel):
    """
    Hold presentation data for one download route.
    """

    route_id: str
    package: str
    package_title: str
    title: str
    filename: str
    version: str
    full_version: str
    file: str
    package_route: str
    download_gate_type: str | None = None
    download_survey: str | None = None
    download_form_header: str | None = None

    @property
    def route_version(self) -> str:
        """
        Return the route-safe version label.
        """
        return route_version(self.version)

    @property
    def option_label(self) -> str:
        """
        Return a concise label for a dataset-page download option.
        """
        file_format = Path(self.filename).suffix.lstrip(".").lower()
        if self.route_id != f"{self.package}_{file_format}":
            return f"Download {file_format.upper()}"
        if file_format == "xlsx":
            return "Download as Excel file (xlsx)"
        if file_format == "json":
            return "Download Json file"
        if file_format == "sqlite":
            return "Download SQLite file"
        return f"Download {self.filename}"


class DatasetVersion(BaseModel):
    """
    Hold a validated published dataset and its derived downloads.
    """

    name: str
    title: str
    description: str
    version: str
    full_version: str
    data: PublishedDataset
    downloads: list[DownloadPage] = Field(default_factory=list)

    @property
    def route_version(self) -> str:
        """
        Return the route-safe version label.
        """
        return route_version(self.version)

    @property
    def is_latest(self) -> bool:
        """
        Return whether this page represents the latest alias.
        """
        return self.version == "latest"


class DatasetVersionList(BaseModel):
    """
    Group all route labels for one dataset by semantic version.
    """

    name: str
    title: str
    versions: list[VersionLabels]


class AnalysisPage(BaseModel):
    """
    Hold a validated notebook bundle ready for rendering.
    """

    manifest: AnalysisBundleManifest
    body_html: str
    bundle_dir: Path

    @property
    def slug(self) -> str:
        """
        Return the route slug from the persisted manifest.
        """
        return self.manifest.slug

    @property
    def title(self) -> str:
        """
        Return the page title from the persisted manifest.
        """
        return self.manifest.title

    @property
    def description(self) -> str:
        """
        Return the description from the persisted manifest.
        """
        return self.manifest.description

    @property
    def order(self) -> int:
        """
        Return the navigation order from the persisted manifest.
        """
        return self.manifest.order

    @property
    def external_css(self) -> list[str]:
        """
        Return external stylesheets declared by the manifest.
        """
        return self.manifest.external_css

    @property
    def external_js(self) -> list[str]:
        """
        Return external scripts declared by the manifest.
        """
        return self.manifest.external_js


class DataIndexFile(BaseModel):
    """
    Describe one downloadable file in data.json.
    """

    url: str
    survey_link: str


class DataIndexVersion(BaseModel):
    """
    Describe one version entry in data.json.
    """

    full_version: str
    files: dict[str, DataIndexFile]


class DatasetDataIndex(BaseModel):
    """
    Describe all published versions of one dataset.
    """

    latest_version: str
    versions: dict[str, DataIndexVersion]


class DataIndex(RootModel[dict[str, DatasetDataIndex]]):
    """
    Validate the complete public data.json mapping.
    """


def route_version(version: str) -> str:
    """
    Convert a dotted version label to its route representation.
    """
    return version.replace(".", "_")
